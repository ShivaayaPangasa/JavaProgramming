package Module5.MavenExamples.Q31_PurposeOfMaven;
/*
Apache Maven is a build automation and project management tool used in Java development. 

It simplifies the process of compiling source code, managing external libraries, running tests, packaging 
applications into JAR or WAR files, and deploying project artifacts.

Maven uses a standard directory structure and a configuration file called pom.xml (Project Object Model). 
It automatically downloads required dependencies from repositories and manages their versions. It also supports
plugins that provide additional build functionality.
Example command:
mvn clean package

This command cleans previous build output and executes the build lifecycle through the package phase, usually
compiling the code, running tests and creating a JAR or WAR when the project is configured accordingly.
*/