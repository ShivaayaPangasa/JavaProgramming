package Module1.Q19_OddEven;

public class OddEven{
    public static void main(String[] args){
        for(int i=1; i<11; i++){
            if (i % 2 != 0){
                System.out.println(i + " " + "Odd");
            }

            else {
                System.out.println(i + " " + "Even");
            }
        }

    }

}